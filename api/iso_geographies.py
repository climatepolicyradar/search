"""
Adds every ISO 3166-1 country and ISO 3166-2 subdivision to the geographies taxonomy.

The labels in `geographies_taxonomy.py` only cover geographies that have documents,
so a country page cannot list the subdivisions that have none (to grey them out).
The additions here are what is left of ISO once those labels are taken out. They
are generated by `scripts/ephemeral/generate_iso_geographies.py` into
`iso_geographies_data.py`.

This is a stopgap. Once the taxonomy is fed from Snowflake and the label
management Wikibase holds every geography, both files can go.
"""

from collections.abc import Sequence

from api.iso_geographies_data import ISO_COUNTRIES, ISO_SUBDIVISIONS
from search.data_in_models import Label, LabelRelationship

# ISO subdivisions that the documents are tagged with under another id. The tagged
# id stays, and the ISO one is left out so a subdivision is not listed twice. Drop
# an entry once its documents have been retagged with the ISO code.
LEGACY_SUBDIVISION_IDS = {
    "subdivision::ES-AN": "subdivision::ES-19572",
    "subdivision::ES-CN": "subdivision::ES-19574",
    "subdivision::IN-TS": "subdivision::IN-TG",
    "subdivision::IN-UK": "subdivision::IN-UT",
    "subdivision::ZA-KZN": "subdivision::ZA-NL",
}


class UnknownParentError(Exception):
    def __init__(self, label_id: str, parent_id: str) -> None:
        super().__init__(f"{label_id} is under {parent_id}, which is not a known label")


class DuplicateLabelError(Exception):
    def __init__(self, label_id: str) -> None:
        super().__init__(f"{label_id} is already in the geographies taxonomy")


def _under(parent: Label | None) -> list[LabelRelationship]:
    return [LabelRelationship(type="subconcept_of", value=parent)] if parent else []


def with_iso_geographies(existing: Sequence[Label]) -> list[Label]:
    """Return `existing` followed by the ISO countries and subdivisions it lacks."""
    labels_by_id = {label.id: label for label in existing}
    added: list[Label] = []

    def add(label_id: str, label_type: str, value: str, parent_id: str | None) -> None:
        if label_id in labels_by_id:
            raise DuplicateLabelError(label_id)

        parent = None
        if parent_id is not None:
            parent_id = LEGACY_SUBDIVISION_IDS.get(parent_id, parent_id)
            if parent_id not in labels_by_id:
                raise UnknownParentError(label_id, parent_id)
            parent = labels_by_id[parent_id]

        label = Label(id=label_id, type=label_type, value=value, labels=_under(parent))
        labels_by_id[label_id] = label
        added.append(label)

    for label_id, value, region_id in ISO_COUNTRIES:
        add(label_id, "country", value, region_id)

    for label_id, value, parent_id in ISO_SUBDIVISIONS:
        add(label_id, "subdivision", value, parent_id)

    return [*existing, *added]
