"""
Regenerate `api/iso_geographies_data.py` from pycountry and the World Bank API.

The output holds the ISO countries and subdivisions that
`api/geographies_taxonomy.py` does not already hold.

    PYTHONPATH=. uv run --with pycountry python scripts/ephemeral/generate_iso_geographies.py
    uv run ruff format api/iso_geographies_data.py

Names: a country takes pycountry's common name, else its ISO name. A subdivision
takes its ISO name without the bracketed alternatives ISO appends ("Wales [Cymru
GB-CYM]").

Regions: a country takes its World Bank region, fetched from the World Bank API.
`REGION_OVERRIDES` fills in or replaces those, for the territories the World Bank
does not classify.

If the import below fails because the current data clashes with a label newly added
to `geographies_taxonomy.py`, empty the two lists in `iso_geographies_data.py` first.
"""

import json
import re
import urllib.request
from pathlib import Path

import pycountry

from api.geographies_taxonomy import snowflake_geographies

OUTPUT = Path(__file__).parents[2] / "api" / "iso_geographies_data.py"
WORLD_BANK_COUNTRIES = "https://api.worldbank.org/v2/country?format=json&per_page=400"
REGION_IDS = {label.id for label in snowflake_geographies if label.type == "region"}

# Territories the World Bank does not classify. Each takes the World Bank region closest
# to its UN M49 region (ENRI-1968). Antarctica has no M49 region, so it stays without one.
REGION_OVERRIDES: dict[str, str] = {
    # Latin America & Caribbean
    "AIA": "region::LCN",
    "BES": "region::LCN",
    "BLM": "region::LCN",
    "BVT": "region::LCN",
    "FLK": "region::LCN",
    "GLP": "region::LCN",
    "GUF": "region::LCN",
    "MSR": "region::LCN",
    "MTQ": "region::LCN",
    "SGS": "region::LCN",
    # East Asia & Pacific
    "CCK": "region::EAS",
    "CXR": "region::EAS",
    "HMD": "region::EAS",
    "NFK": "region::EAS",
    "PCN": "region::EAS",
    "TKL": "region::EAS",
    "UMI": "region::EAS",
    "WLF": "region::EAS",
    # Sub-Saharan Africa
    "ATF": "region::SSF",
    "IOT": "region::SSF",
    "MYT": "region::SSF",
    "REU": "region::SSF",
    "SHN": "region::SSF",
    # Europe & Central Asia
    "ALA": "region::ECS",
    "GGY": "region::ECS",
    "JEY": "region::ECS",
    "SJM": "region::ECS",
    # North America
    "SPM": "region::NAC",
    # Middle East & North Africa
    "ESH": "region::MEA",
}

BRACKETED_SUFFIX = re.compile(r"\s*\[.*\]\s*$")


def world_bank_regions() -> dict[str, str]:
    # WORLD_BANK_COUNTRIES is a constant https URL, so the scheme is not user-controlled.
    with urllib.request.urlopen(WORLD_BANK_COUNTRIES, timeout=30) as response:  # nosec B310
        _, countries = json.load(response)

    regions = {c["id"]: f"region::{c['region']['id']}" for c in countries}
    return {code: region for code, region in regions.items() if region in REGION_IDS}


def country_rows(known_ids: set[str]) -> list[tuple[str, str, str | None]]:
    regions = {**world_bank_regions(), **REGION_OVERRIDES}
    return [
        (
            f"country::{country.alpha_3}",
            getattr(country, "common_name", country.name),
            regions.get(country.alpha_3),
        )
        for country in sorted(pycountry.countries, key=lambda c: c.alpha_3)
        if f"country::{country.alpha_3}" not in known_ids
    ]


def depth(code: str, parents: dict[str, str | None]) -> int:
    parent = parents[code]
    return 0 if parent is None else 1 + depth(parent, parents)


def subdivision_rows(known_ids: set[str]) -> list[tuple[str, str, str]]:
    """Every ISO subdivision not already known, each listed after its parent."""
    subdivisions = {s.code: s for s in pycountry.subdivisions}
    parents = {code: s.parent_code for code, s in subdivisions.items()}

    def parent_id(code: str) -> str:
        parent = parents[code]
        if parent is not None:
            return f"subdivision::{parent}"
        country_code = subdivisions[code].country_code
        country = pycountry.countries.get(alpha_2=country_code)
        if country is None:
            raise ValueError(f"No ISO country for {country_code} ({code})")
        return f"country::{country.alpha_3}"

    return [
        (
            f"subdivision::{code}",
            BRACKETED_SUFFIX.sub("", subdivisions[code].name),
            parent_id(code),
        )
        for code in sorted(subdivisions, key=lambda c: (depth(c, parents), c))
        if f"subdivision::{code}" not in known_ids
    ]


def literal(row: tuple[str, str, str | None]) -> str:
    return (
        "("
        + ", ".join(
            "None" if v is None else json.dumps(v, ensure_ascii=False) for v in row
        )
        + "),"
    )


def main() -> None:
    known_ids = {label.id for label in snowflake_geographies}
    countries = country_rows(known_ids)
    subdivisions = subdivision_rows(known_ids)

    lines = [
        '"""Generated by scripts/ephemeral/generate_iso_geographies.py. Do not edit."""',
        "",
        "ISO_COUNTRIES: list[tuple[str, str, str | None]] = [",
        *(f"    {literal(row)}" for row in countries),
        "]",
        "ISO_SUBDIVISIONS: list[tuple[str, str, str]] = [",
        *(f"    {literal(row)}" for row in subdivisions),
        "]",
        "",
    ]
    OUTPUT.write_text("\n".join(lines))

    unclassified = [code for code, _, region in countries if region is None]
    print(f"{len(countries)} countries, {len(subdivisions)} subdivisions")
    print(f"{len(unclassified)} countries without a region: {', '.join(unclassified)}")


if __name__ == "__main__":
    main()
